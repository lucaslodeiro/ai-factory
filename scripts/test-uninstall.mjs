import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Database from "better-sqlite3";

const source = fileURLToPath(new URL("..",import.meta.url));
const sandbox = fs.mkdtempSync(path.join(os.tmpdir(),"factory-uninstall-"));
try {
  const home=path.join(sandbox,"home"),root=path.join(home,"ai-factory"),data=path.join(home,"factory-data"),target=path.join(home,"Source","target"),agents=path.join(home,"Library","LaunchAgents");
  fs.mkdirSync(path.join(root,"scripts"),{recursive:true}); fs.mkdirSync(data,{recursive:true}); fs.mkdirSync(target,{recursive:true}); fs.mkdirSync(agents,{recursive:true});
  fs.writeFileSync(path.join(root,"package.json"),JSON.stringify({name:"ai-factory"}));
  fs.copyFileSync(path.join(source,"scripts","uninstall.mjs"),path.join(root,"scripts","uninstall.mjs"));
  fs.symlinkSync(path.join(source,"node_modules"),path.join(root,"node_modules"),"dir");
  fs.mkdirSync(path.join(home,".local","bin"),{recursive:true}); fs.symlinkSync(path.join(root,"scripts","ai-factory"),path.join(home,".local","bin","ai-factory"));
  const bin=path.join(sandbox,"bin"),gitLog=path.join(sandbox,"git.log");fs.mkdirSync(bin);
  fs.writeFileSync(path.join(bin,"git"),`#!/bin/sh\nprintf '%s\\n' "$*" >> "$GIT_LOG"\nexit 0\n`,{mode:0o755});
  fs.writeFileSync(path.join(root,".env"),`FACTORY_DATA_DIR=${data}\nFACTORY_REPO_DIR=${target}\nGIT_COMMAND=${path.join(bin,"git")}\n`);
  const database=new Database(path.join(data,"factory.db"));
  database.exec("CREATE TABLE work_items(issue_number INTEGER,stage TEXT,status TEXT,branch TEXT)");
  database.prepare("INSERT INTO work_items VALUES(?,?,?,?)").run(17,"BUILD","PAUSED","factory/issue-17-demo");database.close();
  fs.writeFileSync(path.join(target,"keep"),"target");
  for (const service of ["daemon","dashboard"]) fs.writeFileSync(path.join(agents,`com.ai-factory.${service}.plist`),"fixture");
  fs.writeFileSync(path.join(home,".local-tool"),"keep");
  const testEnv={...process.env,HOME:home,GIT_LOG:gitLog,AI_FACTORY_UNINSTALL_SKIP_LAUNCHCTL:"1"};
  const cancelled=spawnSync(process.execPath,[path.join(root,"scripts","uninstall.mjs")],{cwd:root,env:testEnv,encoding:"utf8"});
  assert.notEqual(cancelled.status,0);
  assert.match(cancelled.stderr,/Re-run with --yes/);
  assert.equal(fs.existsSync(root),true);
  const refused=spawnSync(process.execPath,[path.join(root,"scripts","uninstall.mjs"),"--yes"],{cwd:root,env:testEnv,encoding:"utf8"});
  assert.notEqual(refused.status,0);assert.match(refused.stderr,/--yes --force/);assert.equal(fs.existsSync(root),true);
  assert.match(refused.stdout,/#17 BUILD\/PAUSED — factory\/issue-17-demo \(unpublished\)/);
  const result=spawnSync(process.execPath,[path.join(root,"scripts","uninstall.mjs"),"--yes","--force"],{cwd:root,env:testEnv,encoding:"utf8"});
  assert.equal(result.status,0,result.stderr+result.stdout);
  assert.equal(fs.existsSync(root),false); assert.equal(fs.existsSync(data),false);
  assert.equal(fs.existsSync(path.join(agents,"com.ai-factory.daemon.plist")),false); assert.equal(fs.existsSync(path.join(agents,"com.ai-factory.dashboard.plist")),false);
  assert.equal(fs.existsSync(path.join(home,".local","bin","ai-factory")),false);
  assert.equal(fs.readFileSync(path.join(target,"keep"),"utf8"),"target"); assert.equal(fs.readFileSync(path.join(home,".local-tool"),"utf8"),"keep");
  assert.match(result.stdout,/AI Factory was uninstalled/);
  assert.match(result.stdout,/parent shell may still reference the removed directory/);
  assert.match(fs.readFileSync(gitLog,"utf8"),/ls-remote --heads origin factory\/issue-17-demo/);
  console.log("PASS: uninstall preflights unpublished work, requires force, removes factory services, installation and data while preserving targets and shared tools");
} finally { fs.rmSync(sandbox,{recursive:true,force:true}); }
